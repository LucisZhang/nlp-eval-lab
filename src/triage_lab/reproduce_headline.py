def reproduce(plan: RunPlan, *, skip_data: bool = False, reuse_preds: bool = False,
              results_path=DEFAULT_RESULTS_PATH) -> int:
    """Regenerate the chain and gate it. Returns a process exit code."""
    skipped = {"data"} if skip_data else set()
    if reuse_preds:
        skipped.add("preds")

    before = snapshot_state(plan.gated, plan.dirs)
    stages: list[Stage] = []
    failed = False
    for name, argv in stage_commands(plan):
        stage = Stage(name)
        if name in skipped:
            stage.status = "skipped"
            stage.detail = "skipped by flag (run is PARTIAL)"
            stages.append(stage)
            continue
        if name == "preds" and reuse_preds:
            argv = [a for a in argv if a != "--force"]
        stages.append(_run_stage(stage, argv))
        if not stages[-1].ok:
            failed = True
            break
        if name == "data":
            rows = check_split_identity(plan.runs, results_path=results_path)
            ok = print_check_table("split byte-identity vs the frozen run records:", rows)
            split_stage = Stage("split-gate", "ok" if ok else "FAIL", 0.0,
                                f"{len(rows)} split(s) checked")
            stages.append(split_stage)
            if not ok:
                failed = True
                break

    after = snapshot_state(plan.gated, plan.dirs)
    mismatches = compare_state(before, after) if not failed else []
    masked = masked_only_changes(before, after)
    if failed:
        print("\n(a stage failed; the hash gate was not evaluated)")
    print_report(stages, mismatches, masked, partial=bool(skipped))

    ok = not failed and not mismatches
    print(f"\nreproduce-headline: {'OK' if ok else 'FAILED'}"
          f"{' (PARTIAL)' if skipped and ok else ''}")
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m triage_lab.reproduce_headline",
        description="Re-derive the headline claim chain from the frozen snapshot and gate "
                    "every regenerated file against what is committed.")
    parser.add_argument("--plan", action="store_true",
                        help="resolve and print the chain, check committed inputs, and "
                             "exit; touches nothing under data/ (CI-safe)")
    parser.add_argument("--preflight", action="store_true",
                        help="--plan plus the local prerequisites (make, the tierb extra, "
                             "the Tier B checkpoints and their recorded hashes)")
    parser.add_argument("--skip-data", action="store_true",
                        help="reuse the existing data/splits instead of re-running "
                             "`make data` (marks the run PARTIAL)")
    parser.add_argument("--reuse-preds", action="store_true",
                        help="verify the existing per-example artifacts instead of "
                             "re-deriving them (marks the run PARTIAL)")
    parser.add_argument("--cost-config", type=Path, default=COST_CONFIG_PATH)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS_PATH)
    args = parser.parse_args(argv)

    plan = build_plan(args.cost_config, args.results)
    print_plan(plan)

    ok = print_check_table("committed inputs:",
                           check_committed_inputs(plan.cfg, plan.runs, plan.gated,
                                                  results_path=args.results))
    if args.preflight or not args.plan:
        ok = print_check_table(
            "local prerequisites:",
            check_local_prerequisites(plan.runs, results_path=args.results)) and ok
    if not ok:
        print("\npreflight FAILED — nothing was regenerated")
        return 1
    if args.plan or args.preflight:
        print("\npreflight OK (no stage was run)")
        return 0

    return reproduce(plan, skip_data=args.skip_data, reuse_preds=args.reuse_preds,
                     results_path=args.results)


