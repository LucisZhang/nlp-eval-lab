"""`make reproduce-headline` — one command from the frozen snapshot to the headline claims.

UPGRADE_PLAN §4.3 asks for "a `make reproduce-headline` target [that] re-runs the headline
eval end-to-end on the frozen snapshot". This module is that target's driver. It does two
things that a shell one-liner cannot:

1. **Re-derives** the headline claim chain — frozen snapshot -> splits -> per-example
   prediction artifacts (re-derived, not reused) -> the v2 cost/threshold/router/frontier
   derivation -> the demo payload.
2. **Gates the result against what is committed.** Every file the chain writes is hashed
   BEFORE anything is regenerated and re-hashed after; a single differing byte fails the
   run and names the file. That is what makes the command evidence rather than a rebuild.

Scope: the **headline claim chain** — the certified `a_to_b` router frontier in
`results/frontier/frontier__opv2__cost-2c969255.json` and everything that feeds it, plus
the demo payload that publishes it. Deliberately NOT the whole case-study page: the yearly
drift runs, the 16 perturbation fits, the OOV sweep and the prior-shift decomposition are
each their own multi-hour job, and folding them in would turn the one command into a
multi-day one that nobody runs. Those numbers keep their own repro commands in
EXPERIMENT_LOG.md. This scoping is the owner's, recorded here because a reader is entitled
to know what "reproduce the headline" did and did not touch.

Design decisions, all of them auditable because the verdict depends on them:

- **The run set is RESOLVED from the committed artifacts, never transcribed.** Every
  threshold / router / frontier file names its inputs in an `inputs` block carrying
  `{run_id, config_name, ...}`. `resolve_chain_runs` reads those blocks out of the exact
  files this command regenerates, so the set of runs that gets re-derived is by
  construction the set the committed claims were built from. A hardcoded list would be a
  second source of truth that drifts silently the first time the chain gains a rung.
  The resolved config names are then cross-checked against the constants the chain modules
  actually read (`router_sim`, `threshold_opt`, `demo_build`); a name in the files that no
  module names, or vice versa, is a hard failure rather than a quiet omission.

- **The Tier B cost-model step selects runs by ID, not by `--config-prefix tier_b`.**
  `make tier-b-frontier` prices Tier B with `--config-prefix tier_b`, which was exactly
  right when it was written (2026-08-11): the five Tier B runs that existed were the five
  the chain uses. Phase 5 then added four `tier_b2_distilbert_s0_test_drift_*` runs, and
  that prefix now also selects them — so re-running the command verbatim today would write
  four `results/cost_model/*.json` files that HEAD does not carry, and would fail on a
  fresh clone where those drift artifacts do not exist. Reproducing the headline must
  reproduce the committed file set exactly, so this driver passes the Tier B run ids the
  chain artifacts name. See `EXPERIMENT_LOG.md` (Phase 6, `make reproduce-headline`).

- **`--force` on the artifacts, because "regenerate" is the whole point.**
  `triage_lab.predictions --force` re-invokes each deterministic runner (Tier A refits,
  Tier B re-runs the checkpoint, Tier C rebuilds from the committed receipts — no network)
  and verifies every artifact against its logged point metrics at 1e-9, exiting nonzero on
  any mismatch. It appends nothing to `results/runs.jsonl` (CLAUDE.md rule 3): the run log
  is evidence of what happened, not a scratch pad for reproductions.

- **Split byte-identity is checked against the RUN RECORDS, not against itself.**
  `data/splits/splits_stats.yaml` is regenerated by `make data` alongside the parquets, so
  the runners' "parquet matches its stats file" check cannot catch a split that moved —
  both sides would move together. `check_split_identity` compares the regenerated
  `{split_sha256, input_sha256}` to the `dataset` block frozen in each chain run's record
  in `results/runs.jsonl`, which is committed and append-only. `docs/DATASHEET.md` (also
  regenerated, also committed, and carrying the split hash table) is gated on top.

- **One legitimately varying field, masked by name.** `demo/data/meta.json` embeds
  `git_sha` = HEAD at build time, which changes with every commit and says nothing about
  the numbers. It is masked for the comparison and reported separately, so the mask can
  never hide a real change: `MASKED_FIELDS` is keyed by exact repo-relative path and field
  name, and `tests/test_reproduce_headline.py` proves `git_sha` is the only key of
  `build_meta` that moves when HEAD moves.

Modes (`--plan` and `--preflight` exist so failure is cheap; the default is the real run):

- `--plan`      resolve the chain and check the committed inputs, touching nothing under
                `data/`. Offline, seconds, and safe in CI on a bare clone.
- `--preflight` `--plan` plus the local prerequisites the real run needs — `make`, the
                `tierb` extra (torch/transformers), the Tier B checkpoints with their
                recorded content hashes, the snapshot manifest. Fails in seconds where the
                real run would fail in hours.
- default       preflight -> data -> artifacts -> derivation -> demo -> hash gate -> report.
- `--skip-data` / `--reuse-preds` skip the two expensive stages for iteration. Both mark
                the run **PARTIAL** in the report and in the exit banner: a partial run is
                a debugging aid, never a reproduction claim.
"""

