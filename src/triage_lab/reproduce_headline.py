@dataclass(frozen=True)
class ChainRun:
    """One run whose per-example artifact the headline chain reads."""

    run_id: str
    config_name: str
    split: str
    source: str  # "chain-artifact" | "demo-payload"

    @property
    def short(self) -> str:
        return self.run_id[:8]


def chain_artifact_paths(cfg: cost_model.CostConfig, *,
                         results_path=DEFAULT_RESULTS_PATH,
                         thresholds_dir=DEFAULT_THRESHOLDS_DIR,
                         router_dir=DEFAULT_ROUTER_DIR,
                         frontier_dir=DEFAULT_FRONTIER_DIR) -> list[Path]:
    """The committed derivation files this command regenerates, in chain order.

    Names are BUILT from the same helpers the writers use (`threshold_opt.result_filename`
    et al. are not importable without their objects, so the naming pattern is rebuilt from
    the same inputs: the cost config's hash and the v2 CAL rung's run id). The threshold
    family files are globbed on that pair rather than listed, because the family set is a
    property of the cost config (Tier B families exist only when Tier B is priced).
    """
    sha8 = cfg.sha256[:8]
    records = predictions.records_by_config(results_path)
    cal_config = threshold_opt.V2_TIER_A_CAL_CONFIG
    if cal_config not in records:
        raise ValueError(
            f"no run record for the v2 CAL rung {cal_config!r} in {_rel(results_path)}; "
            "the threshold files cannot be located"
        )
    cal8 = records[cal_config]["run_id"][:8]

    thresholds = sorted(Path(thresholds_dir).glob(f"*__{cal8}__cost-{sha8}.json"))
    summary_name = threshold_opt.DERIVATIONS[DERIVATION]["summary_name"].format(sha8=sha8)
    thresholds.append(Path(thresholds_dir) / summary_name)

    router = [Path(router_dir) / router_sim.result_filename(name, cfg, OP_VERSION)
              for name in (router_sim.EVAL_FULL, router_sim.EVAL_PAIRED, "summary")]
    front = [Path(frontier_dir) / frontier.result_filename(cfg, OP_VERSION)]
    return [*thresholds, *router, *front]


def _artifact_blocks(obj):
    """Yield every `{run_id, config_name, ...}` provenance block in a derivation file."""
    if isinstance(obj, dict):
        if isinstance(obj.get("run_id"), str) and isinstance(obj.get("config_name"), str):
            yield obj
        for value in obj.values():
            yield from _artifact_blocks(value)
    elif isinstance(obj, list):
        for value in obj:
            yield from _artifact_blocks(value)


def referenced_runs(paths) -> dict[str, dict[str, str]]:
    """run_id -> {config_name, split} over every input block in the given files.

    A run id that appears under two different config names is a hard failure: it would mean
    two derivation files disagree about what a run is, and the driver would have no rule for
    which one to re-derive.
    """
    out: dict[str, dict[str, str]] = {}
    for path in paths:
        obj = json.loads(Path(path).read_text(encoding="utf-8"))
        for block in _artifact_blocks(obj):
            entry = {"config_name": block["config_name"],
                     "split": block.get("split", "")}
            previous = out.setdefault(block["run_id"], entry)
            if previous["config_name"] != entry["config_name"]:
                raise ValueError(
                    f"run {block['run_id'][:8]} is named {previous['config_name']!r} and "
                    f"{entry['config_name']!r} by different derivation files in the chain"
                )
    return out


def resolve_chain_runs(cfg: cost_model.CostConfig, *,
                       results_path=DEFAULT_RESULTS_PATH,
                       **dirs) -> list[ChainRun]:
    """Every run whose artifact must be re-derived, resolved from committed evidence.

    Order is stable (config name), so the printed plan and the `predictions` invocation are
    reproducible line for line.
    """
    paths = chain_artifact_paths(cfg, results_path=results_path, **dirs)
    missing = [p for p in paths if not p.exists()]
    if missing:
        raise ValueError(
            "cannot resolve the headline chain: committed derivation file(s) missing — "
            + ", ".join(_rel(p) for p in missing)
        )
    referenced = referenced_runs(paths)
    records = predictions.records_by_config(results_path)

    runs = [ChainRun(run_id=run_id, config_name=info["config_name"],
                     split=info["split"], source="chain-artifact")
            for run_id, info in referenced.items()]
    known = {r.config_name for r in runs}
    for config_name in DEMO_ONLY_CONFIGS:
        if config_name in known:
            continue
        if config_name not in records:
            raise ValueError(
                f"no run record for demo input {config_name!r} in {_rel(results_path)}"
            )
        record = records[config_name]
        runs.append(ChainRun(run_id=record["run_id"], config_name=config_name,
                             split=(record.get("dataset") or {}).get("split", ""),
                             source="demo-payload"))

    resolved = {r.config_name for r in runs}
    expected = chain_module_configs()
    if resolved != expected:
        raise ValueError(
            "the run set named by the committed chain artifacts disagrees with the config "
            "stems the chain modules read — a rung was added, renamed or removed and this "
            f"driver must be updated. only in artifacts: {sorted(resolved - expected)}; "
            f"only in modules: {sorted(expected - resolved)}"
        )
    return sorted(runs, key=lambda r: (r.config_name, r.run_id))


def tier_b_run_ids(runs) -> list[str]:
    """The Tier B runs the v2 cost model re-scores (see the module header's second note)."""
    return [r.run_id for r in runs if r.config_name.startswith(TIER_B_CONFIG_PREFIX)]


