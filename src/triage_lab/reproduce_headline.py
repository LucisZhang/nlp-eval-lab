def _digest_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def file_digests(path) -> tuple[str, str]:
    """`(raw_sha256, compare_sha256)` for one gated file.

    The two differ only for a path in `MASKED_FIELDS`, where the compare digest is taken
    over the payload with those fields blanked. Both are kept so the report can say
    "identical except git_sha" instead of "identical", which would be a lie by omission.
    """
    raw = Path(path).read_bytes()
    raw_sha = _digest_bytes(raw)
    fields = MASKED_FIELDS.get(_rel(path))
    if not fields:
        return raw_sha, raw_sha
    obj = json.loads(raw)
    for name in fields:
        if name not in obj:
            raise ValueError(
                f"{_rel(path)} has no field {name!r} to mask; MASKED_FIELDS is stale and "
                "the comparison would be silently unmasked"
            )
        obj[name] = ""
    return raw_sha, _digest_bytes(json.dumps(obj, sort_keys=True).encode("utf-8"))


def snapshot_state(paths, dirs) -> dict:
    """`{files: {rel: (raw, compare)}, listings: {rel_dir: [rel_file...]}}` before/after."""
    files = {}
    for path in paths:
        path = Path(path)
        files[_rel(path)] = file_digests(path) if path.exists() else None
    listings = {
        _rel(d): sorted(_rel(p) for p in Path(d).glob("*") if p.is_file())
        for d in dirs if Path(d).exists()
    }
    return {"files": files, "listings": listings}


def compare_state(before: dict, after: dict) -> list[dict]:
    """Differences between two `snapshot_state` results, one row per finding."""
    rows: list[dict] = []
    for rel, before_digest in before["files"].items():
        after_digest = after["files"].get(rel)
        if before_digest is None:
            rows.append({"path": rel, "kind": "absent-before",
                         "detail": "file did not exist before the run"})
            continue
        if after_digest is None:
            rows.append({"path": rel, "kind": "missing",
                         "detail": "the chain did not write this file"})
            continue
        if before_digest[1] != after_digest[1]:
            rows.append({
                "path": rel, "kind": "changed",
                "detail": f"{before_digest[1][:12]} -> {after_digest[1][:12]}",
            })
    for rel_dir, before_files in before["listings"].items():
        after_files = after["listings"].get(rel_dir, [])
        for extra in sorted(set(after_files) - set(before_files)):
            rows.append({"path": extra, "kind": "unexpected-new",
                         "detail": f"not present in {rel_dir} before the run"})
        for gone in sorted(set(before_files) - set(after_files)):
            rows.append({"path": gone, "kind": "deleted",
                         "detail": f"removed from {rel_dir} by the run"})
    return rows


def masked_only_changes(before: dict, after: dict) -> list[str]:
    """Files whose raw bytes moved but whose masked comparison did not (expected: meta)."""
    out = []
    for rel, before_digest in before["files"].items():
        after_digest = after["files"].get(rel)
        if before_digest and after_digest and before_digest != after_digest \
                and before_digest[1] == after_digest[1]:
            out.append(rel)
    return sorted(out)


