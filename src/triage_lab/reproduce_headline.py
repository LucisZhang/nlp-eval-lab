def _row(check: str, ok: bool, detail: str) -> dict:
    return {"check": check, "ok": bool(ok), "detail": detail}


def check_committed_inputs(cfg: cost_model.CostConfig, runs, gated,
                           *, results_path=DEFAULT_RESULTS_PATH) -> list[dict]:
    """Repo-only prerequisites: no `data/`, no torch, no network. CI-safe.

    Config hashes go through `predictions.load_config_checked`, the same gate the artifact
    backfill uses, so "the config changed since the run" is caught here in a second rather
    than after an hour of refitting.
    """
    rows = [_row("results_log", Path(results_path).exists(), _rel(results_path)),
            _row("cost_config", Path(cfg.path).exists(),
                 f"{_rel(cfg.path)} sha256={cfg.sha256[:12]} ({cfg.version})")]

    missing = [_rel(p) for p in gated if not Path(p).exists()]
    rows.append(_row(
        "gated_files_present", not missing,
        f"{len(gated)} committed output(s) to gate" if not missing
        else f"{len(missing)} missing: {missing[:5]}"))

    records = {r["run_id"]: r for r in predictions.load_records(results_path)}
    bad_config, missing_record, missing_receipts = [], [], []
    for run in runs:
        record = records.get(run.run_id)
        if record is None:
            missing_record.append(run.short)
            continue
        try:
            predictions.load_config_checked(record)
        except Exception as exc:  # noqa: BLE001 — reported as a check row, not raised
            bad_config.append(f"{run.config_name}: {exc}")
        if run.config_name.startswith(TIER_C_CONFIG_PREFIX):
            raw = (record.get("extra") or {}).get("raw_log_path", "")
            if not raw or not (REPO_ROOT / raw).exists():
                missing_receipts.append(f"{run.config_name} -> {raw or '<unset>'}")

    rows.append(_row("run_records", not missing_record,
                     f"{len(runs)} chain run(s) resolve in the log" if not missing_record
                     else f"no record for {missing_record}"))
    rows.append(_row("config_hashes", not bad_config,
                     "every chain config still hashes as its run logged"
                     if not bad_config else "; ".join(bad_config)))
    rows.append(_row(
        "tier_c_receipts", not missing_receipts,
        "committed per-call receipts present (Tier C rebuilds offline)"
        if not missing_receipts else f"missing: {missing_receipts}"))
    return rows


def check_local_prerequisites(runs, *, results_path=DEFAULT_RESULTS_PATH) -> list[dict]:
    """What the real run needs on this machine, checked before it costs hours.

    The Tier B checkpoints are the expensive failure: they are NOT in git (they are
    gigabytes of weights), so a fresh clone reaches the Tier B stage hours in and dies
    there. Here they fail in seconds, by name, with the runbook that says how to get them —
    and their weights are hashed against the `extra.checkpoint_sha256` each run recorded,
    so a truncated or wrong-seed download is caught too.
    """
    rows = [_row("make", shutil.which("make") is not None,
                 shutil.which("make") or "`make` not on PATH; the data stage shells out "
                                          "to `make data`")]

    missing_deps = [name for name in ("torch", "transformers")
                    if importlib.util.find_spec(name) is None]
    rows.append(_row(
        "tierb_extra", not missing_deps,
        "torch + transformers importable" if not missing_deps
        else f"{missing_deps} not importable — re-run under "
             "`uv run --extra tierb` (Tier B artifacts cannot be re-derived without it)"))

    manifest = DEFAULT_SNAPSHOT_MANIFEST
    rows.append(_row("snapshot_manifest", manifest.exists(),
                     f"{_rel(manifest)} (the snapshot itself is downloaded and "
                     "sha256-verified by `make snapshot`)"))

    records = {r["run_id"]: r for r in predictions.load_records(results_path)}
    problems: list[str] = []
    checked: list[str] = []
    for run in runs:
        if not run.config_name.startswith(TIER_B_CONFIG_PREFIX):
            continue
        record = records.get(run.run_id) or {}
        config = predictions.load_config_checked(record)
        ckpt = Path((config.get("model") or {}).get("checkpoint", ""))
        ckpt = ckpt if ckpt.is_absolute() else REPO_ROOT / ckpt
        if not ckpt.is_dir():
            problems.append(f"{run.config_name}: {_rel(ckpt)} absent")
            continue
        if missing_deps:
            checked.append(f"{_rel(ckpt)} present (hash unchecked: no torch)")
            continue
        from triage_lab import tier_b  # local: importing it needs the tierb extra

        try:
            actual = tier_b.checkpoint_content_hash(ckpt)
        except FileNotFoundError as exc:
            problems.append(f"{run.config_name}: {exc}")
            continue
        logged = (record.get("extra") or {}).get("checkpoint_sha256", "")
        if logged and actual != logged:
            problems.append(
                f"{run.config_name}: {_rel(ckpt)} weights hash {actual[:12]} but run "
                f"{run.short} logged {logged[:12]}")
        else:
            checked.append(f"{_rel(ckpt)}={actual[:12]}")
    rows.append(_row(
        "tier_b_checkpoints", not problems,
        "; ".join(sorted(set(checked))) if not problems
        else f"{problems} — checkpoints are not in git; see docs/TIER_B_RUNBOOK.md "
             "(download the trained dirs into data/checkpoints/<name>/)"))
    return rows


def check_split_identity(runs, *, results_path=DEFAULT_RESULTS_PATH,
                         splits_stats_path=harness.DEFAULT_SPLITS_STATS_PATH) -> list[dict]:
    """Regenerated splits must hash to what the frozen run records say (CLAUDE.md rule 2).

    Compared against `results/runs.jsonl` — committed, append-only — and not against
    `splits_stats.yaml`'s own copy, which `make data` rewrites in lockstep with the
    parquets and therefore cannot contradict them.
    """
    if not Path(splits_stats_path).exists():
        return [_row("split_identity", False,
                     f"{_rel(splits_stats_path)} absent; `make data` did not materialize "
                     "the splits")]
    records = {r["run_id"]: r for r in predictions.load_records(results_path)}
    seen: dict[str, dict] = {}
    for run in runs:
        record = records.get(run.run_id) or {}
        split = (record.get("dataset") or {}).get("split", "")
        if split and split not in seen:
            seen[split] = record["dataset"]

    rows = []
    for split in sorted(seen):
        logged = seen[split]
        actual = harness.dataset_info(split, splits_stats_path)
        ok = (actual["split_sha256"] == logged.get("split_sha256")
              and actual["input_sha256"] == logged.get("input_sha256"))
        rows.append(_row(
            f"split::{split}", ok,
            f"sha256={str(actual['split_sha256'])[:12]} matches the frozen run records" if ok
            else (f"regenerated {str(actual['split_sha256'])[:12]} / snapshot "
                  f"{str(actual['input_sha256'])[:12]} vs logged "
                  f"{str(logged.get('split_sha256'))[:12]} / "
                  f"{str(logged.get('input_sha256'))[:12]}")))
    return rows


# ---------------------------------------------------------------------------
# Stages
# ---------------------------------------------------------------------------

@dataclass
class Stage:
    name: str
    status: str = "pending"
    seconds: float = 0.0
    detail: str = ""

    @property
    def ok(self) -> bool:
        return self.status in {"ok", "skipped"}


@dataclass
class RunPlan:
    """Everything the driver resolved before it touched anything."""

    cfg: cost_model.CostConfig
    runs: list[ChainRun]
    gated: list[Path]
    dirs: list[Path] = field(default_factory=gated_dirs)

    @property
    def run_ids(self) -> list[str]:
        return [r.run_id for r in self.runs]


def build_plan(cost_config_path=COST_CONFIG_PATH,
               results_path=DEFAULT_RESULTS_PATH) -> RunPlan:
    cfg = cost_model.load_cost_config(cost_config_path)
    if not cost_model.prices_tier_b(cfg):
        raise ValueError(
            f"cost config {Path(cfg.path).name} does not price Tier B; the headline chain "
            "is a Tier A -> Tier B router and cannot be derived under it"
        )
    runs = resolve_chain_runs(cfg, results_path=results_path)
    return RunPlan(cfg=cfg, runs=runs,
                   gated=gated_files(cfg, runs, results_path=results_path))


def _module_cmd(module: str, *args: str) -> list[str]:
    """Run a chain CLI in THIS interpreter, so the Makefile's `--extra tierb` carries."""
    return [sys.executable, "-m", module, *args]


def stage_commands(plan: RunPlan) -> list[tuple[str, list[str]]]:
    """(stage name, argv) for every stage that regenerates something, in order."""
    cost_config = str(plan.cfg.path)
    return [
        ("data", [os.environ.get("MAKE", "make"), "data"]),
        ("preds", _module_cmd("triage_lab.predictions", "--force", *plan.run_ids)),
        ("cost-model", _module_cmd("triage_lab.cost_model", *tier_b_run_ids(plan.runs),
                                   "--cost-config", cost_config)),
        ("thresholds", _module_cmd("triage_lab.threshold_opt", "--derivation", DERIVATION,
                                   "--cost-config", cost_config)),
        ("router-sim", _module_cmd("triage_lab.router_sim", "--op-version", OP_VERSION,
                                   "--cost-config", cost_config)),
        ("frontier", _module_cmd("triage_lab.frontier", "--op-version", OP_VERSION,
                                 "--cost-config", cost_config)),
        ("demo-data", _module_cmd("triage_lab.demo_build", "--all")),
    ]


def _run_stage(stage: Stage, argv: list[str]) -> Stage:
    print(f"\n=== stage {stage.name}: {' '.join(argv)}", flush=True)
    started = time.monotonic()
    # argv is built in this module from repo constants and resolved run ids — never from
    # user input — and runs with `check=False` so a failing stage is reported, not raised.
    completed = subprocess.run(argv, cwd=REPO_ROOT, check=False)
    stage.seconds = time.monotonic() - started
    stage.status = "ok" if completed.returncode == 0 else "FAIL"
    stage.detail = f"exit {completed.returncode}"
    return stage


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

def print_check_table(title: str, rows) -> bool:
    print(f"\n{title}")
    for row in rows:
        print(f"  {'✓' if row['ok'] else '✗'} {row['check']:22s} {row['detail']}")
    return all(row["ok"] for row in rows)


def print_plan(plan: RunPlan) -> None:
    print(f"cost config     {_rel(plan.cfg.path)} sha256={plan.cfg.sha256[:12]}")
    print(f"operating point {OP_VERSION}  headline_router={demo_build.HEADLINE_ROUTER}")
    print(f"\nchain runs ({len(plan.runs)} artifacts re-derived with --force):")
    for run in plan.runs:
        print(f"  {run.short}  {run.config_name:36s} {run.split:10s} [{run.source}]")
    print(f"\ngated outputs ({len(plan.gated)} committed file(s) hashed before and after):")
    for path in plan.gated:
        print(f"  {_rel(path)}")
    print("\nstages:")
    for name, argv in stage_commands(plan):
        print(f"  {name:12s} {' '.join(argv)}")


def print_report(stages, mismatches, masked, *, partial: bool) -> None:
    print("\n" + "=" * 78)
    print("reproduce-headline report")
    print("=" * 78)
    print(f"  {'stage':14s} {'status':8s} {'wall_clock':>12s}  detail")
    for stage in stages:
        print(f"  {stage.name:14s} {stage.status:8s} {stage.seconds:11.1f}s  "
              f"{stage.detail}")
    total = sum(s.seconds for s in stages)
    print(f"  {'TOTAL':14s} {'':8s} {total:11.1f}s")

    if masked:
        print("\nidentical under the declared mask (raw bytes differ in that field only):")
        for rel in masked:
            print(f"  ~ {rel}  [{', '.join(MASKED_FIELDS[rel])}]")
    if mismatches:
        print(f"\n✗ {len(mismatches)} gated output(s) do not match what is committed:")
        for row in mismatches:
            print(f"  ✗ {row['kind']:16s} {row['path']}  {row['detail']}")
    else:
        print("\n✓ every gated output is byte-identical to the committed record")

    if partial:
        print("\nPARTIAL: stages were skipped — this run is a debugging aid, NOT a "
              "reproduction claim.")


